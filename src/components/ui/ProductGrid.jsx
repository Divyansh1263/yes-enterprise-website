import { useLanguage } from '../../i18n'
import ProductCard from './ProductCard'

export default function ProductGrid({ products, emptyMessage }) {
  const { t } = useLanguage()
  const empty = emptyMessage || t('products.emptyTitle')

  if (!products || products.length === 0) {
    return (
      <div className="text-center py-20">
        <div className="w-16 h-16 bg-gray-100 rounded-2xl flex items-center justify-center mx-auto mb-4 text-gray-300">
          <svg className="w-8 h-8" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M20 13V6a2 2 0 00-2-2H6a2 2 0 00-2 2v7m16 0v5a2 2 0 01-2 2H6a2 2 0 01-2-2v-5m16 0h-2.586a1 1 0 00-.707.293l-2.414 2.414a1 1 0 01-.707.293h-3.172a1 1 0 01-.707-.293l-2.414-2.414A1 1 0 006.586 13H4" />
          </svg>
        </div>
        <p className="text-gray-700 font-medium mb-1">{empty}</p>
        <p className="text-gray-400 text-sm">{t('products.emptyHint')}</p>
      </div>
    )
  }

  return (
    <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-3 gap-5">
      {products.map(p => <ProductCard key={p.id} product={p} />)}
    </div>
  )
}
